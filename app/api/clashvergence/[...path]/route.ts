import { NextRequest, NextResponse } from "next/server";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

const MAX_REQUEST_BYTES = 8 * 1024 * 1024;
const REQUEST_TIMEOUT_MS = 90_000;
const MAX_RATE_BUCKETS = 10_000;

type RatePolicy = {
  name: string;
  limit: number;
  windowMs: number;
};

type RateBucket = {
  count: number;
  expiresAt: number;
};

const RATE_POLICIES: Record<string, RatePolicy> = {
  create: { name: "create", limit: 6, windowMs: 10 * 60_000 },
  advance: { name: "advance", limit: 480, windowMs: 60_000 },
  history: { name: "history", limit: 6, windowMs: 60 * 60_000 },
  standard: { name: "standard", limit: 240, windowMs: 60_000 }
};

const rateBuckets = new Map<string, RateBucket>();

type RouteContext = {
  params: { path: string[] };
};

type Operation = "create" | "state" | "delete" | "advance" | "history";

function errorResponse(error: string, status: number, headers: Record<string, string> = {}) {
  return NextResponse.json(
    { error },
    { status, headers: { "cache-control": "no-store", ...headers } }
  );
}

function allowedOperations(path: string[]): Partial<Record<string, Operation>> | null {
  if (path[0] !== "demo" || path[1] !== "sessions") return null;
  if (path.length === 2) return { POST: "create" };

  // demo_server.py accepts only IDs generated by uuid4().hex.
  const sessionId = path[2];
  if (sessionId?.length !== 32 || !/^[0-9a-f]{32}$/.test(sessionId)) return null;
  if (path.length === 3) return { GET: "state", DELETE: "delete" };
  if (path.length === 4 && (path[3] === "advance" || path[3] === "history")) {
    return { POST: path[3] };
  }
  return null;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function validPayload(operation: Operation, value: unknown): boolean {
  if (!isObject(value)) return false;
  const keys = Object.keys(value);
  if (operation === "advance") return keys.length === 0;
  if (operation === "history") {
    return (
      keys.every((key) => key === "faction_name" || key === "length") &&
      typeof value.faction_name === "string" && value.faction_name.length > 0 &&
      (value.length === undefined ||
        value.length === "abridged" || value.length === "standard" || value.length === "long")
    );
  }
  if (operation === "create") {
    // Preserve backend defaults; configured upper limits and map internals stay upstream.
    return (
      keys.every((key) => ["map", "num_factions", "seed", "target_turns"].includes(key)) &&
      isObject(value.map) &&
      (value.num_factions === undefined ||
        (Number.isSafeInteger(value.num_factions) && (value.num_factions as number) >= 2)) &&
      (value.target_turns === undefined ||
        (Number.isSafeInteger(value.target_turns) && (value.target_turns as number) >= 1)) &&
      (value.seed === undefined || value.seed === null || typeof value.seed === "string")
    );
  }
  return false;
}

function clientIdentity(request: NextRequest): string {
  const forwardedFor = request.headers.get("x-forwarded-for")?.split(",", 1)[0];
  const candidate = request.ip || request.headers.get("x-real-ip") || forwardedFor;
  return (candidate?.trim() || "unknown").slice(0, 128);
}

function ratePolicy(method: string, path: string[]): RatePolicy {
  if (method === "POST" && path.length === 2) return RATE_POLICIES.create;
  if (method === "POST" && path.at(-1) === "advance") return RATE_POLICIES.advance;
  if (method === "POST" && path.at(-1) === "history") return RATE_POLICIES.history;
  return RATE_POLICIES.standard;
}

function enforceRateLimit(
  request: NextRequest,
  path: string[]
): { allowed: boolean; retryAfterSeconds: number } {
  const now = Date.now();
  const policy = ratePolicy(request.method, path);
  const key = `${policy.name}:${clientIdentity(request)}`;
  let bucket = rateBuckets.get(key);

  if (bucket && now >= bucket.expiresAt) {
    rateBuckets.delete(key);
    bucket = undefined;
  }

  if (!bucket && rateBuckets.size >= MAX_RATE_BUCKETS) {
    rateBuckets.forEach((candidate, candidateKey) => {
      if (now >= candidate.expiresAt) rateBuckets.delete(candidateKey);
    });
    if (rateBuckets.size >= MAX_RATE_BUCKETS) {
      return { allowed: false, retryAfterSeconds: 60 };
    }
  }

  if (!bucket) {
    rateBuckets.set(key, {
      count: 1,
      expiresAt: now + policy.windowMs
    });
    return { allowed: true, retryAfterSeconds: 0 };
  }

  if (bucket.count >= policy.limit) {
    return {
      allowed: false,
      retryAfterSeconds: Math.max(
        1,
        Math.ceil((bucket.expiresAt - now) / 1_000)
      )
    };
  }

  bucket.count += 1;
  return { allowed: true, retryAfterSeconds: 0 };
}

function backendBaseUrl(): URL | null {
  const rawUrl = process.env.CLASHVERGENCE_API_URL?.trim();
  if (!rawUrl) return null;

  try {
    const url = new URL(rawUrl);
    const isLocalHttp =
      url.protocol === "http:" &&
      (url.hostname === "127.0.0.1" || url.hostname === "localhost");
    if (url.username || url.password || (url.protocol !== "https:" && !isLocalHttp)) {
      return null;
    }
    return url;
  } catch {
    return null;
  }
}

function backendRequestUrl(baseUrl: URL, path: string[]): URL {
  const basePath = baseUrl.pathname.endsWith("/")
    ? baseUrl.pathname
    : `${baseUrl.pathname}/`;
  const encodedPath = path.map(encodeURIComponent).join("/");
  const target = new URL(baseUrl);
  target.pathname = `${basePath}${encodedPath}`.replace(/\/{2,}/g, "/");
  target.search = "";
  return target;
}

async function proxy(request: NextRequest, context: RouteContext) {
  const operations = allowedOperations(context.params.path);
  if (!operations) return errorResponse("Unknown demo endpoint.", 404);
  const operation = Object.prototype.hasOwnProperty.call(operations, request.method)
    ? operations[request.method]
    : undefined;
  if (!operation) {
    return errorResponse("Method not allowed.", 405, { Allow: Object.keys(operations).join(", ") });
  }
  if (request.nextUrl.search) {
    return errorResponse("Demo endpoints do not accept query parameters.", 400);
  }

  const baseUrl = backendBaseUrl();
  if (!baseUrl) {
    return NextResponse.json(
      { error: "The Clashvergence demo service is not configured." },
      { status: 503 }
    );
  }

  const target = backendRequestUrl(baseUrl, context.params.path);

  const rateLimit = enforceRateLimit(request, context.params.path);
  if (!rateLimit.allowed) {
    return NextResponse.json(
      { error: "Too many demo requests. Please wait and try again." },
      {
        status: 429,
        headers: {
          "cache-control": "no-store",
          "retry-after": String(rateLimit.retryAfterSeconds)
        }
      }
    );
  }

  const declaredLength = Number(request.headers.get("content-length") ?? 0);
  if (Number.isFinite(declaredLength) && declaredLength > MAX_REQUEST_BYTES) {
    return NextResponse.json({ error: "Demo request is too large." }, { status: 413 });
  }

  let body: ArrayBuffer | undefined;
  if (request.method !== "GET") {
    try {
      body = await request.arrayBuffer();
    } catch {
      return errorResponse("Unable to read demo request.", 400);
    }
    if (body.byteLength > MAX_REQUEST_BYTES) {
      return NextResponse.json({ error: "Demo request is too large." }, { status: 413 });
    }
    if (operation === "delete" && body.byteLength !== 0) {
      return errorResponse("Delete requests must not include a body.", 400);
    }
    if (request.method === "POST") {
      const contentType = request.headers.get("content-type")?.split(";", 1)[0].trim().toLowerCase();
      if (contentType !== "application/json") {
        return errorResponse("Content-Type must be application/json.", 415);
      }
      try {
        const payload: unknown = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(body));
        if (!validPayload(operation, payload)) {
          return errorResponse("Unsupported demo request data.", 400);
        }
      } catch {
        return errorResponse("Request body must be valid UTF-8 JSON.", 400);
      }
    }
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const forwardHeaders: Record<string, string> = {};
    if (body) {
      forwardHeaders["content-type"] =
        request.headers.get("content-type") ?? "application/json";
    }
    const proxySecret = process.env.CLASHVERGENCE_DEMO_PROXY_SECRET?.trim();
    if (proxySecret) {
      forwardHeaders["x-clashvergence-proxy-secret"] = proxySecret;
    }

    const response = await fetch(target, {
      method: request.method,
      body,
      headers: forwardHeaders,
      cache: "no-store",
      signal: controller.signal
    });
    const responseBody = await response.arrayBuffer();
    const responseHeaders = new Headers();
    responseHeaders.set(
      "content-type",
      response.headers.get("content-type") ?? "application/json; charset=utf-8"
    );
    const requestId = response.headers.get("x-request-id");
    if (requestId) responseHeaders.set("x-request-id", requestId);
    responseHeaders.set("cache-control", "no-store");

    return new NextResponse(responseBody, {
      status: response.status,
      headers: responseHeaders
    });
  } catch (error) {
    const timedOut = error instanceof Error && error.name === "AbortError";
    return NextResponse.json(
      {
        error: timedOut
          ? "The Clashvergence service took too long to respond."
          : "The Clashvergence service is unavailable."
      },
      { status: timedOut ? 504 : 502 }
    );
  } finally {
    clearTimeout(timeout);
  }
}

export function GET(request: NextRequest, context: RouteContext) {
  return proxy(request, context);
}

export function POST(request: NextRequest, context: RouteContext) {
  return proxy(request, context);
}

export function DELETE(request: NextRequest, context: RouteContext) {
  return proxy(request, context);
}
